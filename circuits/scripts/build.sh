#!/usr/bin/env bash
# Compile the Hidden Vault circuits and (re)generate their Solidity verifiers.
#   bash circuits/scripts/build.sh            # writes contracts/src/consumer/verifiers/*Verifier.sol
#   OUT_DIR=/tmp/x bash circuits/scripts/build.sh   # writes elsewhere (freshness test)
# Toolchain versions are pinned in circuits/VERSIONS.
set -euo pipefail
export PATH="$HOME/.nargo/bin:$HOME/.bb:$PATH"
here="$(cd "$(dirname "$0")/.." && pwd)"
out="${OUT_DIR:-$here/../contracts/src/consumer/verifiers}"
mkdir -p "$out"

want() { grep "^$1=" "$here/VERSIONS" | cut -d= -f2; }
nargo --version | grep -q "nargo version = $(want nargo)$" || { echo "nargo $(want nargo) required (noirup -v $(want nargo))" >&2; exit 1; }
[ "$(bb --version)" = "$(want bb)" ] || { echo "bb $(want bb) required (bbup -v $(want bb))" >&2; exit 1; }

(cd "$here/poseidon2_fixture" && nargo compile --silence-warnings >/dev/null)
for c in transfer withdraw threshold_holdings threshold_savings swap settle treasury_close; do
  Name="$(perl -pe 's/(?:^|_)(.)/\u$1/g' <<<"$c")"
  (cd "$here/$c" && nargo compile --silence-warnings >/dev/null)
  bb write_vk -b "$here/$c/target/$c.json" -o "$here/$c/target" -t evm >/dev/null 2>&1
  tmp="$(mktemp)"
  bb write_solidity_verifier -k "$here/$c/target/vk" -o "$tmp" -t evm >/dev/null 2>&1
  # Give each generated verifier a unique contract name so both can live in one build.
  { echo "// GENERATED by circuits/scripts/build.sh from circuits/$c (bb $(want bb), noir $(want nargo)). Do not edit."
    perl -pe "s/\\bHonkVerificationKey\\b/${Name}VerificationKey/g; s/^contract HonkVerifier /contract ${Name}Verifier /; s/^pragma solidity [^;]+;/pragma solidity 0.8.28;/" "$tmp"
  } | perl -p "$here/scripts/mark-not-a-key.pl" > "$out/${Name}Verifier.sol"
  rm -f "$tmp"
  echo "$c: $(grep -o '"circuit_size": [0-9]*' <(bb gates -b "$here/$c/target/$c.json" 2>/dev/null)) -> $out/${Name}Verifier.sol"
done
