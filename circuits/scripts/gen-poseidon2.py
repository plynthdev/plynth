import re
# Regenerates contracts/src/consumer/verifiers/Poseidon2.sol from Barretenberg's parameters.
#   gh api 'repos/AztecProtocol/aztec-packages/contents/barretenberg/cpp/src/barretenberg/crypto/poseidon2/poseidon2_params.hpp?ref=v5.2.0' \
#     --jq .content | base64 -d > /tmp/params.hpp
#   python3 circuits/scripts/gen-poseidon2.py /tmp/params.hpp
import os, subprocess, sys
src=open(sys.argv[1]).read()
# take only the Poseidon2Bn254ScalarFieldParams struct
body=src.split('struct Poseidon2Bn254ScalarFieldParams')[1]
diag_blk=body.split('internal_matrix_diagonal_minus_one = {')[1].split('};')[0]
diag=re.findall(r'0x[0-9a-f]{64}',diag_blk)
rc_blk=body.split('> round_constants{')[1]
rc=re.findall(r'0x[0-9a-f]{64}',rc_blk)[:64*4]
assert len(diag)==4 and len(rc)==256
RC=[rc[i*4:(i+1)*4] for i in range(64)]
L=[]
w=L.append
w('// SPDX-License-Identifier: MIT')
w('pragma solidity ^0.8.28;')
w('')
w('/// @title Poseidon2 (bn254, t = 4, d = 5, 8 full + 56 partial rounds) and the Hidden Vault sponge')
w('/// @notice Bit-for-bit equal to Noir\'s `std::hash::poseidon2_permutation` (Barretenberg backend) and')
w('///         to `circuits/hidden` `hash()` (stdlib Poseidon2Hasher: rate 3, capacity 1, IV = len << 64).')
w('/// @dev GENERATED from barretenberg v5.2.0 crypto/poseidon2/poseidon2_params.hpp (Apache-2.0, original')
w('///      parameters by Horizen Labs). Equality with Noir is proven on 100 random inputs per function by')
w('///      contracts/test/consumer/verifiers/Poseidon2.t.sol against fixtures produced by nargo/noir_js.')
w('library Poseidon2 {')
w('    uint256 internal constant P = 21888242871839275222246405745257275088548364400416034343698204186575808495617;')
w('')
w('    error NotAFieldElement();')
w('')
w('    /// @notice The raw Poseidon2 permutation over a 4-element state.')
w('    function permutation(uint256[4] memory s) internal pure returns (uint256[4] memory out) {')
w('        (out[0], out[1], out[2], out[3]) = _perm(s[0] % P, s[1] % P, s[2] % P, s[3] % P);')
w('    }')
w('')
w('    function hash1(uint256 a) internal pure returns (uint256 h) {')
w('        _check(a);')
w('        (h,,,) = _perm(a, 0, 0, 1 << 64);')
w('    }')
w('')
w('    function hash2(uint256 a, uint256 b) internal pure returns (uint256 h) {')
w('        _check(a);')
w('        _check(b);')
w('        (h,,,) = _perm(a, b, 0, 2 << 64);')
w('    }')
w('')
w('    function hash3(uint256 a, uint256 b, uint256 c) internal pure returns (uint256 h) {')
w('        _check(a);')
w('        _check(b);')
w('        _check(c);')
w('        // A full rate block is absorbed and permuted, then the (empty) tail is permuted again.')
w('        (uint256 s0, uint256 s1, uint256 s2, uint256 s3) = _perm(a, b, c, 3 << 64);')
w('        (h,,,) = _perm(s0, s1, s2, s3);')
w('    }')
w('')
w('    function hash4(uint256 a, uint256 b, uint256 c, uint256 d) internal pure returns (uint256 h) {')
w('        _check(a);')
w('        _check(b);')
w('        _check(c);')
w('        _check(d);')
w('        (uint256 s0, uint256 s1, uint256 s2, uint256 s3) = _perm(a, b, c, 4 << 64);')
w('        (h,,,) = _perm(addmod(s0, d, P), s1, s2, s3);')
w('    }')
w('')
w('    function _check(uint256 x) private pure {')
w('        if (x >= P) revert NotAFieldElement();')
w('    }')
w('')
w('    function _perm(uint256 a, uint256 b, uint256 c, uint256 d)')
w('        private')
w('        pure')
w('        returns (uint256, uint256, uint256, uint256)')
w('    {')
w('        assembly ("memory-safe") {')
w('            // Every Yul helper hard-codes the bn254 scalar modulus P to keep the stack shallow.')
w('            function sbox(x) -> y {')
w('                let t := mulmod(x, x, PMOD)')
w('                t := mulmod(t, t, PMOD)')
w('                y := mulmod(x, t, PMOD)')
w('            }')
w('            // External 4x4 MDS layer [[5,7,1,3],[4,6,1,1],[1,3,5,7],[1,1,4,6]] (Poseidon2 paper).')
w('            function ext(x0, x1, x2, x3) -> y0, y1, y2, y3 {')
w('                let t0 := addmod(x0, x1, PMOD)')
w('                let t1 := addmod(x2, x3, PMOD)')
w('                let t2 := addmod(addmod(x1, x1, PMOD), t1, PMOD)')
w('                let t3 := addmod(addmod(x3, x3, PMOD), t0, PMOD)')
w('                y3 := addmod(mulmod(t1, 4, PMOD), t3, PMOD)')
w('                y1 := addmod(mulmod(t0, 4, PMOD), t2, PMOD)')
w('                y0 := addmod(t3, y1, PMOD)')
w('                y2 := addmod(t2, y3, PMOD)')
w('            }')
w('            // Internal layer: x_i * (D_i - 1) + sum(x).')
w('            function inner(x0, x1, x2, x3) -> y0, y1, y2, y3 {')
w('                let s := addmod(addmod(x0, x1, PMOD), addmod(x2, x3, PMOD), PMOD)')
for i in range(4):
    w(f'                y{i} := addmod(mulmod(x{i}, {diag[i]}, PMOD), s, PMOD)')
w('            }')
w('            a, b, c, d := ext(a, b, c, d)')
for r in range(64):
    if r<4 or r>=60:
        w(f'            a, b, c, d := ext(sbox(addmod(a, {RC[r][0]}, PMOD)), sbox(addmod(b, {RC[r][1]}, PMOD)), sbox(addmod(c, {RC[r][2]}, PMOD)), sbox(addmod(d, {RC[r][3]}, PMOD)))')
    else:
        w(f'            a, b, c, d := inner(sbox(addmod(a, {RC[r][0]}, PMOD)), b, c, d)')
w('        }')
w('        return (a, b, c, d);')
w('    }')
w('}')
out='\n'.join(L)+'\n'
out=out.replace('PMOD','21888242871839275222246405745257275088548364400416034343698204186575808495617')
here=os.path.dirname(os.path.abspath(__file__))
dst=os.path.join(here,'..','..','contracts/src/consumer/verifiers/Poseidon2.sol')
open(dst,'w').write(out)
subprocess.run(['perl','-pi',os.path.join(here,'mark-not-a-key.pl'),dst],check=True)
