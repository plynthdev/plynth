// Evaluates Noir's Poseidon2 on 100 seeded-random inputs per function (via the
// poseidon2_fixture circuit executed by the ACVM) and writes:
//   contracts/test/consumer/verifiers/fixtures/poseidon2.json   (forge equality test)
//   contracts/src/consumer/verifiers/HiddenConstants.sol        (depth, zero leaf, zero subtrees)
// Run: bash circuits/scripts/build.sh && bun circuits/scripts/fixtures.ts
import { Noir } from "@noir-lang/noir_js";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { P, TREE_DEPTH, ZERO_LEAF, hex } from "./note";

const root = join(import.meta.dir, "..", "..");
export const FIXTURE_PATH = join(root, "contracts/test/consumer/verifiers/fixtures/poseidon2.json");
export const CONSTANTS_SOL = join(root, "contracts/src/consumer/verifiers/HiddenConstants.sol");
const N = 100;

/** Deterministic field elements: sha256("plynth.p2.fixture" | tag | i) mod p. */
const rand = (tag: string, i: number) =>
  BigInt("0x" + createHash("sha256").update(`plynth.p2.fixture|${tag}|${i}`).digest("hex")) % P;

export async function computeFixtures() {
  const program = JSON.parse(readFileSync(join(import.meta.dir, "../poseidon2_fixture/target/poseidon2_fixture.json"), "utf8"));
  const states = Array.from({ length: N }, (_, i) => [0, 1, 2, 3].map((k) => rand(`s${k}`, i)));
  // Include edge values in the first rows.
  states[0] = [0n, 0n, 0n, 0n];
  states[1] = [P - 1n, P - 1n, P - 1n, P - 1n];
  const cols = ["a", "b", "c", "d"].map((t) => Array.from({ length: N }, (_, i) => rand(t, i)));
  cols.forEach((col) => ((col[0] = 0n), (col[1] = P - 1n)));
  const noir = new Noir(program);
  const toStr = (x: bigint) => hex(x);
  const { returnValue } = await noir.execute({
    states: states.map((s) => s.map(toStr)),
    a: cols[0]!.map(toStr),
    b: cols[1]!.map(toStr),
    c: cols[2]!.map(toStr),
    d: cols[3]!.map(toStr),
  });
  const [perms, h1, h2, h3, h4, zeros] = returnValue as [string[][], string[], string[], string[], string[], string[]];
  // Decimal strings: forge parses them as uint, and 0x-64-hex would trip public-guard.
  const norm = (x: string | bigint) => BigInt(x).toString();
  const dec = (x: bigint) => x.toString();
  return {
    note: "Generated by circuits/scripts/fixtures.ts from Noir (ACVM) execution of circuits/poseidon2_fixture.",
    states: states.map((s) => s.map(dec)),
    perms: perms.map((s) => s.map(norm)),
    a: cols[0]!.map(dec),
    b: cols[1]!.map(dec),
    c: cols[2]!.map(dec),
    d: cols[3]!.map(dec),
    h1: h1.map(norm),
    h2: h2.map(norm),
    h3: h3.map(norm),
    h4: h4.map(norm),
    zeros: zeros.map(norm),
  };
}

export function constantsSol(zeros: string[]): string {
  if (zeros.length !== TREE_DEPTH + 1 || BigInt(zeros[0]!) !== ZERO_LEAF) throw new Error("zeros mismatch");
  const lines = zeros.map((z, i) => `        if (level == ${i}) return ${hex(BigInt(z))}; // not-a-key`);
  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.28;

// GENERATED by circuits/scripts/fixtures.ts from circuits/constants.json. Do not edit.
// The same values are in circuits/hidden/src/constants.nr; zero subtrees come from Noir.

/// @title Hidden Vault shared constants (tree depth, empty leaf, empty-subtree roots)
library HiddenConstants {
    /// @notice Depth of the note commitment tree.
    uint256 internal constant TREE_DEPTH = ${TREE_DEPTH};
    /// @notice Empty leaf: keccak256("plynth.hidden.zero-leaf") mod p.
    uint256 internal constant ZERO_LEAF = ${hex(ZERO_LEAF)}; // not-a-key
    /// @notice Root of an empty tree of depth TREE_DEPTH.
    uint256 internal constant EMPTY_ROOT = ${hex(BigInt(zeros[TREE_DEPTH]!))}; // not-a-key

    error LevelOutOfRange();

    /// @notice Root of an empty subtree of height \`level\` (0 = ZERO_LEAF, TREE_DEPTH = EMPTY_ROOT).
    function zeros(uint256 level) internal pure returns (uint256) {
${lines.join("\n")}
        revert LevelOutOfRange();
    }
}
`;
}

if (import.meta.main) {
  const fx = await computeFixtures();
  mkdirSync(join(FIXTURE_PATH, ".."), { recursive: true });
  writeFileSync(FIXTURE_PATH, JSON.stringify(fx, null, 1) + "\n");
  writeFileSync(CONSTANTS_SOL, constantsSol(fx.zeros));
  console.log(`wrote ${FIXTURE_PATH}\nwrote ${CONSTANTS_SOL}`);
}
